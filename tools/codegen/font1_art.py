PICTOGRAMS = {"TICK": "{", "CROSS": "|", "SMILEY": "}", "HEART": "~"}
FIRST_CP, LAST_CP = 32, 126


def row_bits(row: str) -> int:
    if len(row) != CELL_W:
        raise ValueError(f"row {row!r} is not {CELL_W} wide")
    v = 0
    for i, ch in enumerate(row):
        if ch == "#":
            v |= 1 << (CELL_W - 1 - i)
        elif ch not in "._":
            raise ValueError(f"row {row!r} may only contain '#', '.' and '_'")
    return v


def build() -> dict:
    glyphs = []
    for cp in range(FIRST_CP, LAST_CP + 1):
        art = ART.get(chr(cp))
        if art is None:
            raise SystemExit(f"missing 5x7 art for {chr(cp)!r} ({cp})")
        if len(art) != CELL_H:
            raise SystemExit(f"glyph {chr(cp)!r} has {len(art)} rows, expected {CELL_H}")
        glyphs.append({"codepoint": cp, "rows": [row_bits(r) for r in art]})
    return {
        "id": 1,
        "name": "builtin_5x7",
        "cell_width": CELL_W,
        "cell_height": CELL_H,
        "advance": ADVANCE,
        "first_codepoint": FIRST_CP,
        "glyph_count": len(glyphs),
        "pictograms": PICTOGRAMS,
        "glyphs": glyphs,
    }


if __name__ == "__main__":
    font = build()
    OUT_JSON.write_text(json.dumps(font, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT_JSON} — {font['glyph_count']} glyphs, "
          f"{font['glyph_count'] * CELL_H} bytes of table")
